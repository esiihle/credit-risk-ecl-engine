"""
The synthetic loan book — and the analytic truth that goes with it.

WHY SIMULATE
------------
The deliverable of this project is the **correctness of a calculation**, not a
finding about a population. That distinction decides the data strategy.

A real loan book would be more realistic and completely useless for the job in
hand, because nobody knows a real book's true probability of default. Here the
data-generating process is written down, so the true 12-month PD, the true
lifetime PD, the exact exposure schedule and the true loss given default are all
*known*. The engine's output can therefore be checked against an answer derived
analytically rather than against another estimate.

Every artefact this module produces is labelled synthetic. A simulated figure
that does not say it is simulated is the worst bug this portfolio has had.

THE MODEL
---------
Delinquency is a discrete-time Markov chain over arrears buckets:

    0 = current      1 = 1-29 DPD      2 = 30-59 DPD
    3 = 60-89 DPD    4 = 90+ DPD (default, absorbing)

Each account has its own monthly transition matrix P, built from the base rates
in `config.yaml` scaled by its segment's risk multiplier and by a seasoning
curve (default risk peaks part-way through a loan's life, not at origination).

Because P is known, the truth follows exactly:

    P(default within k months | currently in bucket s) = (P^k)[s, 4]

No simulation needed for the truth — only for the data the engine will see.
That is the whole point: the engine estimates, and `analytic_pd` already knows.

EXPOSURE
--------
A fixed-term amortising loan's balance schedule is deterministic given
principal, rate and term, so EAD at any future month is exact arithmetic:

    instalment = P * i / (1 - (1 + i)^-n)
    balance_t  = P * ((1+i)^n - (1+i)^t) / ((1+i)^n - 1)
"""
import json
from functools import lru_cache
from pathlib import Path

import numpy as np
import pandas as pd

# Bucket labels, used everywhere rather than bare integers.
BUCKETS = {0: "current", 1: "1-29 DPD", 2: "30-59 DPD",
           3: "60-89 DPD", 4: "90+ DPD (default)"}
DEFAULT_BUCKET = 4
N_BUCKETS = len(BUCKETS)

# Stamped onto every table this module writes, so no downstream consumer can
# mistake generated data for an observed book.
SYNTHETIC_NOTICE = (
    "SYNTHETIC — generated by src/generate.py from a known data-generating "
    "process. Not a real loan book. The true PD, EAD and LGD are recoverable "
    "and are used to check the engine's output."
)


class GeneratorError(Exception):
    """Raised when the requested book cannot be generated."""


# ---------------------------------------------------------------------------
# The transition matrix: the ground truth everything else is derived from
# ---------------------------------------------------------------------------

def seasoning_factor(months_on_book, config):
    """How much riskier than baseline an account is at this age.

    Default risk on a term loan is low immediately after origination (the
    borrower has just been underwritten and has just received the money), rises
    to a peak somewhere in the first couple of years, then falls as the
    survivors reveal themselves to be good payers. A flat hazard would make the
    vintage analysis in a later phase meaningless, because every cohort would
    look identical.

    Modelled as a gamma-like bump peaking at `seasoning_peak_month`.
    """
    cfg = config["generator"]
    peak = float(cfg["seasoning_peak_month"])
    strength = float(cfg["seasoning_strength"])

    age = np.asarray(months_on_book, dtype=float)
    # Normalised age; the bump is x * exp(1 - x), which equals 1 at x = 1.
    x = np.maximum(age, 0.0) / peak
    bump = np.where(x > 0, x * np.exp(1.0 - x), 0.0)
    return 1.0 + strength * (bump - 1.0)


@lru_cache(maxsize=4096)
def _cached_matrix(risk_multiplier, months_on_book, config_key):
    """Memoised matrix build. See `transition_matrix` for the real docstring.

    The cache key includes a config fingerprint so a changed config cannot be
    served a stale matrix — a cache that silently outlives its inputs is the
    kind of bug this portfolio keeps finding.
    """
    config = _CONFIG_REGISTRY[config_key]
    return _build_transition_matrix(risk_multiplier, months_on_book, config)


_CONFIG_REGISTRY = {}


def _config_key(config):
    """A hashable identity for a config, for use as a cache key."""
    generator = config["generator"]
    key = (id(config), json.dumps(generator, sort_keys=True, default=str))
    _CONFIG_REGISTRY[key] = config
    return key


def transition_matrix(risk_multiplier, months_on_book, config):
    """The monthly transition matrix for one account at one age. Memoised."""
    return _cached_matrix(float(risk_multiplier), int(months_on_book),
                          _config_key(config))


def _build_transition_matrix(risk_multiplier, months_on_book, config):
    """The monthly transition matrix for one account at one age.

    Rows are the current bucket, columns the next. Row 4 (default) is absorbing.
    Probabilities are clipped to [0, 1] and each row is renormalised, so the
    matrix is always stochastic no matter what multiplier is applied — a matrix
    whose rows do not sum to 1 produces nonsense that looks like a result.
    """
    base = config["generator"]["base_transitions"]
    scale = float(risk_multiplier) * float(seasoning_factor(months_on_book, config))

    matrix = np.zeros((N_BUCKETS, N_BUCKETS), dtype=float)

    # From current: either miss a payment or stay current.
    miss = np.clip(base["miss_from_current"] * scale, 0.0, 0.95)
    matrix[0, 1] = miss
    matrix[0, 0] = 1.0 - miss

    # From each arrears bucket: cure, worsen, or stay.
    #
    # The risk multiplier scales WORSENING only, not curing. A first version
    # scaled both — multiplying the worsen rate and dividing the cure rate —
    # and the effect compounded across four buckets into a 135x difference
    # between prime and subprime default rates. No real book shows that. The
    # modelling statement is now explicit: riskier borrowers fall behind more
    # often, but conditional on being 30 days down, they cure at similar rates.
    for bucket in (1, 2, 3):
        cure = np.clip(base[f"cure_from_{bucket}"], 0.0, 0.95)
        worsen = np.clip(base[f"worsen_from_{bucket}"] * scale, 0.0, 0.95)

        total = cure + worsen
        if total > 0.98:                     # leave room to stay put
            cure, worsen = cure * 0.98 / total, worsen * 0.98 / total

        matrix[bucket, bucket - 1] = cure
        matrix[bucket, bucket + 1] = worsen
        matrix[bucket, bucket] = 1.0 - cure - worsen

    # Default is absorbing. Cures out of default (which do happen in reality)
    # are deliberately excluded: IFRS 9 Stage 3 accounting is complicated by
    # them, and this project's job is the core mechanics.
    matrix[DEFAULT_BUCKET, DEFAULT_BUCKET] = 1.0

    return matrix


def cumulative_pd_curve(risk_multiplier, start_bucket, months_on_book,
                        horizon, config):
    """P(default by month t) for t = 0..horizon, in ONE forward pass.

    This is THE ground truth. The engine estimates the same quantity from
    simulated histories; the tests assert the two agree.

    The matrix is age-dependent because of seasoning, so this is a product of
    matrices rather than a single matrix power. Crucially it is computed once
    and sliced, not recomputed per horizon: the first version called a
    fixed-horizon routine for every t, making the whole curve O(T^2) in matrix
    builds. At 10,000 accounts and a 36-month term that was several million
    matrix constructions and dominated the entire generator's runtime.
    """
    horizon = int(horizon)
    curve = np.zeros(horizon + 1)
    if horizon <= 0:
        return curve
    if start_bucket == DEFAULT_BUCKET:
        curve[:] = 1.0
        return curve

    state = np.zeros(N_BUCKETS)
    state[start_bucket] = 1.0

    for step in range(horizon):
        matrix = transition_matrix(risk_multiplier, months_on_book + step, config)
        state = state @ matrix
        curve[step + 1] = state[DEFAULT_BUCKET]

    return curve


def analytic_pd(risk_multiplier, start_bucket, months_on_book, horizon, config):
    """P(default within `horizon` months). The curve's last point."""
    if horizon <= 0:
        return 0.0
    curve = cumulative_pd_curve(risk_multiplier, start_bucket, months_on_book,
                                horizon, config)
    return float(curve[-1])


def marginal_pd_schedule(risk_multiplier, start_bucket, months_on_book,
                         horizon, config):
    """P(defaults in month t), for t = 1..horizon.

    ECL needs the MARGINAL probability of defaulting in each period, not the
    cumulative one — each period's expected loss is discounted from its own
    date. The differences are guaranteed non-negative because the chain is
    absorbing: once in default, always in default, so the curve cannot fall.
    """
    curve = cumulative_pd_curve(risk_multiplier, start_bucket, months_on_book,
                                horizon, config)
    return np.diff(curve)


# ---------------------------------------------------------------------------
# Exposure: deterministic, so exact
# ---------------------------------------------------------------------------

def monthly_rate(annual_rate):
    """Nominal annual rate to a monthly rate, compounding monthly."""
    return (1.0 + annual_rate) ** (1.0 / 12.0) - 1.0


def instalment(principal, annual_rate, term_months):
    """The level monthly payment that amortises the loan over its term."""
    i = monthly_rate(annual_rate)
    if i <= 0:
        return principal / term_months
    return principal * i / (1.0 - (1.0 + i) ** (-term_months))


def balance_at(principal, annual_rate, term_months, month):
    """Outstanding balance after `month` payments. Exact, by the annuity formula.

    This is the exposure at default for a performing account, and because it is
    arithmetic rather than an estimate, every EAD the engine produces can be
    checked to the cent.

    Works on scalars or arrays. The array case is not a convenience: the
    simulator advances the whole book a month at a time, and a scalar-only
    version forces a Python loop over 20,000 accounts for every month.
    """
    principal = np.asarray(principal, dtype=float)
    annual_rate = np.asarray(annual_rate, dtype=float)
    term_months = np.asarray(term_months, dtype=float)

    i = monthly_rate(annual_rate)
    month = np.clip(np.asarray(month, dtype=float), 0.0, term_months)

    # Straight-line fallback where the rate is zero or negative; np.where
    # evaluates both branches, so the annuity arm is guarded against a
    # divide-by-zero that would otherwise emit a warning on a value never used.
    safe_i = np.where(i > 0, i, 1e-9)
    growth = (1.0 + safe_i) ** term_months
    annuity = principal * (growth - (1.0 + safe_i) ** month) / (growth - 1.0)
    straight_line = principal * (1.0 - month / np.maximum(term_months, 1.0))

    result = np.where(i > 0, annuity, straight_line)
    return float(result) if result.ndim == 0 else result


# ---------------------------------------------------------------------------
# Building the book
# ---------------------------------------------------------------------------

def _month_ends(start, end):
    """Month-end dates from start to end inclusive."""
    return pd.date_range(pd.Timestamp(start), pd.Timestamp(end), freq="ME")


def build_accounts(config, rng):
    """Originate the accounts. One row per loan, fixed at origination.

    Everything here is known on day one: who the borrower is, what they
    borrowed, over what term, at what rate, and — because this is simulated —
    their true risk multiplier and true LGD.
    """
    portfolio = config["portfolio"]
    n = int(portfolio["n_accounts"])

    names = list(portfolio["segments"].keys())
    shares = [portfolio["segments"][s]["share"] for s in names]
    segments = rng.choice(names, size=n, p=shares)
    multipliers = np.array([portfolio["segments"][s]["risk_multiplier"]
                            for s in segments])

    origination_dates = _month_ends(portfolio["origination_start"],
                                    portfolio["origination_end"])
    if len(origination_dates) == 0:
        raise GeneratorError(
            "No origination months between "
            f"{portfolio['origination_start']} and {portfolio['origination_end']}."
        )
    originated = rng.choice(origination_dates, size=n)

    # Principal is lognormal-ish within the configured band: most loans small,
    # a tail of large ones, which is what a real book looks like.
    raw = rng.lognormal(mean=np.log(28000), sigma=0.75, size=n)
    principal = np.clip(raw, portfolio["principal_min"],
                        portfolio["principal_max"]).round(2)

    term = rng.choice(portfolio["term_months_choices"], size=n)

    # Riskier borrowers are priced higher — true of every real book, and it
    # gives the discounting step something to bite on.
    rate_low, rate_high = (portfolio["nominal_annual_rate_min"],
                           portfolio["nominal_annual_rate_max"])
    risk_position = (multipliers - multipliers.min()) / max(
        multipliers.max() - multipliers.min(), 1e-9)
    rate = (rate_low + risk_position * (rate_high - rate_low)
            + rng.normal(0, 0.012, n)).clip(rate_low, rate_high).round(4)

    # True LGD per account, Beta-distributed around the configured mean.
    cfg = config["generator"]
    mean, concentration = float(cfg["lgd_mean"]), float(cfg["lgd_concentration"])
    alpha, beta = mean * concentration, (1 - mean) * concentration
    true_lgd = rng.beta(alpha, beta, n).round(4)

    return pd.DataFrame({
        "account_id": [f"ACC{i + 1:06d}" for i in range(n)],
        "segment": segments,
        "origination_date": pd.to_datetime(originated),
        "principal": principal,
        "term_months": term.astype(int),
        "annual_rate": rate,
        "instalment": [round(float(instalment(p, r, t)), 2)
                       for p, r, t in zip(principal, rate, term)],
        # --- ground truth, known only because this book is simulated ---
        "true_risk_multiplier": multipliers,
        "true_lgd": true_lgd,
    })


def simulate_performance(accounts, config, rng):
    """Walk every account month by month through the arrears chain.

    Produces the fact table the engine will actually consume: one row per
    account per month it is on book, with the arrears bucket and the balance.
    The engine sees only these observable columns — never the transition matrix
    that produced them.

    VECTORISED ACROSS ACCOUNTS. The obvious implementation loops over accounts
    and then over months, and took 30 seconds for 2,000 accounts — five minutes
    for a full book, for something that gets regenerated on every parameter
    change. The structure that makes the loop avoidable: the transition matrix
    depends only on the SEGMENT's risk multiplier and the month on book, and
    there are three segments. So each month, three matrices are built and every
    account is advanced with one vectorised categorical draw.
    """
    reporting_date = pd.Timestamp(config["portfolio"]["reporting_date"])

    n = len(accounts)
    multipliers = accounts["true_risk_multiplier"].to_numpy()
    terms = accounts["term_months"].to_numpy()
    principals = accounts["principal"].to_numpy()
    rates = accounts["annual_rate"].to_numpy()
    originated = accounts["origination_date"].to_numpy()
    ids = accounts["account_id"].to_numpy()

    # How many months each account can be observed for: capped by its term and
    # by how long ago it was originated.
    months_available = np.array([
        _months_between(start, reporting_date) for start in accounts["origination_date"]
    ])
    observable = np.minimum(terms, np.maximum(months_available, -1))

    distinct_multipliers = np.unique(multipliers)
    state = np.zeros(n, dtype=int)
    # `alive` means: on book, and not yet absorbed into default.
    alive = observable >= 0

    chunks = []
    max_months = int(observable.max()) + 1

    for month in range(max_months):
        active = alive & (month <= observable)
        if not active.any():
            break

        index = np.flatnonzero(active)
        scheduled = balance_at(principals[index], rates[index],
                               terms[index], month)

        chunks.append(pd.DataFrame({
            "account_id": ids[index],
            "reporting_date": pd.to_datetime(originated[index])
                              + pd.offsets.MonthEnd(0) + pd.DateOffset(months=month),
            "months_on_book": month,
            "arrears_bucket": state[index],
            "scheduled_balance": np.round(scheduled, 2),
            "is_default": state[index] == DEFAULT_BUCKET,
        }))

        # Accounts that have just been recorded in default stop here: the state
        # is absorbing, so there is nothing further to simulate for them.
        alive[index[state[index] == DEFAULT_BUCKET]] = False

        advancing = alive & (month < observable)
        if not advancing.any():
            continue

        # One matrix per segment per month, then a single vectorised draw.
        for multiplier in distinct_multipliers:
            group = np.flatnonzero(advancing & (multipliers == multiplier))
            if group.size == 0:
                continue

            matrix = transition_matrix(multiplier, month, config)
            cumulative = matrix[state[group]].cumsum(axis=1)
            draw = rng.random(group.size)
            # The categorical sample: how many cumulative boundaries the draw
            # clears is the index of the bucket it lands in.
            state[group] = (draw[:, None] > cumulative).sum(axis=1)

    frame = pd.concat(chunks, ignore_index=True) if chunks else pd.DataFrame()
    if frame.empty:
        raise GeneratorError(
            "No performance rows were generated. Check that the reporting date "
            "is after the origination window."
        )

    frame = frame.sort_values(["account_id", "months_on_book"]).reset_index(drop=True)
    # Days past due, derived from the bucket. Staging rules work in DPD because
    # that is what a real collections system records; the bucket is internal to
    # the generator.
    frame["days_past_due"] = frame["arrears_bucket"].map(
        {0: 0, 1: 15, 2: 45, 3: 75, 4: 100}).astype(int)
    return frame


def ground_truth(accounts, config):
    """The answer key: true PD, EAD and ECL per account at the reporting date.

    Computed analytically from the transition matrix and the amortisation
    schedule — never from the simulated paths. That independence is what makes
    it a check rather than a restatement: if the engine and this function agree,
    two different routes reached the same number.
    """
    reporting_date = pd.Timestamp(config["portfolio"]["reporting_date"])
    horizon_12 = int(config["ecl"]["horizon_months_stage_1"])
    rows = []

    for account in accounts.itertuples(index=False):
        months_on_book = _months_between(account.origination_date, reporting_date)
        if months_on_book < 0 or months_on_book > account.term_months:
            continue

        remaining = int(account.term_months - months_on_book)
        if remaining <= 0:
            continue

        # Truth is computed from the CURRENT bucket, which for this answer key
        # is taken as performing. The engine must use the observed bucket; the
        # comparison in tests is like-for-like on performing accounts.
        # One curve serves both horizons and the marginal schedule.
        curve = cumulative_pd_curve(account.true_risk_multiplier, 0,
                                    months_on_book, remaining, config)
        pd_12 = float(curve[min(horizon_12, remaining)])
        pd_lifetime = float(curve[-1])
        marginal = np.diff(curve)
        exposures = np.array([
            balance_at(account.principal, account.annual_rate,
                       account.term_months, months_on_book + t)
            for t in range(1, remaining + 1)
        ])
        i = monthly_rate(account.annual_rate)
        discounts = 1.0 / (1.0 + i) ** np.arange(1, remaining + 1)

        ecl_lifetime = float((marginal * account.true_lgd * exposures * discounts).sum())
        months_12 = min(horizon_12, remaining)
        ecl_12 = float((marginal[:months_12] * account.true_lgd
                        * exposures[:months_12] * discounts[:months_12]).sum())

        rows.append({
            "account_id": account.account_id,
            "months_on_book": months_on_book,
            "remaining_term": remaining,
            "true_balance": round(float(balance_at(
                account.principal, account.annual_rate,
                account.term_months, months_on_book)), 2),
            "true_pd_12m": pd_12,
            "true_pd_lifetime": pd_lifetime,
            "true_lgd": account.true_lgd,
            "true_ecl_12m": ecl_12,
            "true_ecl_lifetime": ecl_lifetime,
        })

    return pd.DataFrame(rows)


def _months_between(start, end):
    """Whole months from start to end."""
    start, end = pd.Timestamp(start), pd.Timestamp(end)
    return (end.year - start.year) * 12 + (end.month - start.month)


def generate_book(config, rng=None):
    """Everything, in one call. Returns (accounts, performance, truth)."""
    if rng is None:
        rng = np.random.default_rng(config.get("seed", 42))

    accounts = build_accounts(config, rng)
    performance = simulate_performance(accounts, config, rng)
    truth = ground_truth(accounts, config)
    return accounts, performance, truth
